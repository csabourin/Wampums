-- Volunteer shifts (#1251): what an activity or camp needs, by type and time slot, and who signed up.
-- A volunteer (a cook, a camp aide) takes part without any access to youth or health records:
-- the built-in volunteer role holds only volunteers.view and tasks.view.
-- Types and the requirements each one carries (a background check for a camp aide…) are listed in
-- config/volunteer_shifts.json; the checks below must list the same keys
-- (test/volunteer-types.test.js). Every type requires a background check. A place on a shift whose
-- requirements the person does not meet is held, pending, until a manager records them.
SELECT setval(pg_get_serial_sequence('public.permissions', 'id'),
  COALESCE((SELECT MAX(id) FROM public.permissions), 0) + 1, false);
INSERT INTO public.permissions (permission_key, permission_name, category, description)
VALUES
  ('volunteers.view', 'See volunteer shifts and sign up', 'volunteers', 'List open shifts, sign up and withdraw oneself; no access to youth records'),
  ('volunteers.manage', 'Manage volunteer shifts', 'volunteers', 'Create, edit and remove shifts, and see or remove who signed up')
ON CONFLICT (permission_key) DO NOTHING;

INSERT INTO public.roles (role_name, display_name, description, data_scope, is_system_role, organization_id)
VALUES ('volunteer', 'Volunteer', 'Signs up for volunteer shifts and follows assigned tasks; no access to youth or health records', 'organization', TRUE, NULL)
ON CONFLICT (role_name) DO NOTHING;

INSERT INTO public.role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM public.roles r CROSS JOIN public.permissions p
WHERE r.role_name = 'volunteer' AND r.organization_id IS NULL
  AND p.permission_key IN ('volunteers.view', 'tasks.view')
ON CONFLICT DO NOTHING;

-- The unit's management (and roles a unit customized from it) organizes shifts; leaders may
-- sign up too. The demo roles see the screen, read-only.
INSERT INTO public.role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM public.roles r
LEFT JOIN public.roles original ON original.id = r.customized_from_role_id
CROSS JOIN public.permissions p
WHERE (
    (p.permission_key IN ('volunteers.view', 'volunteers.manage')
      AND ((r.organization_id IS NULL AND r.role_name IN ('unitadmin', 'demoadmin'))
        OR (r.organization_id IS NOT NULL AND original.organization_id IS NULL AND original.role_name = 'unitadmin')))
    OR (p.permission_key = 'volunteers.view'
      AND ((r.organization_id IS NULL AND r.role_name = 'leader')
        OR (r.organization_id IS NOT NULL AND original.organization_id IS NULL AND original.role_name = 'leader')))
  )
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS public.volunteer_shifts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  activity_id INTEGER NOT NULL,
  volunteer_type VARCHAR(30) NOT NULL DEFAULT 'other'
    CHECK (volunteer_type IN ('camp_aide', 'cook', 'driver', 'night_watch', 'first_aid', 'other')),
  title VARCHAR(120) NOT NULL DEFAULT '',
  shift_date DATE NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL CHECK (end_time > start_time),
  slots INTEGER NOT NULL CHECK (slots BETWEEN 1 AND 50),
  notes TEXT NOT NULL DEFAULT '' CHECK (length(notes) <= 1000),
  created_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (activity_id, organization_id) REFERENCES public.activities(id, organization_id) ON DELETE CASCADE,
  UNIQUE (id, organization_id)
);
CREATE INDEX IF NOT EXISTS volunteer_shifts_by_date ON public.volunteer_shifts (organization_id, shift_date, start_time, id);
CREATE INDEX IF NOT EXISTS volunteer_shifts_by_activity ON public.volunteer_shifts (organization_id, activity_id);

CREATE TABLE IF NOT EXISTS public.volunteer_signups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER NOT NULL,
  shift_id INTEGER NOT NULL,
  user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  status VARCHAR(20) NOT NULL DEFAULT 'confirmed' CHECK (status IN ('pending', 'confirmed')),
  confirmed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (shift_id, organization_id) REFERENCES public.volunteer_shifts(id, organization_id) ON DELETE CASCADE,
  UNIQUE (shift_id, user_id)
);
CREATE INDEX IF NOT EXISTS volunteer_signups_by_user ON public.volunteer_signups (organization_id, user_id);

-- What a manager verified for one person in one unit: a requirement and how long it stays valid.
-- Only the fact and the dates are kept, never the document itself. A background check is required
-- of every adult of the unit (its team, and anyone taking a volunteer shift); it records the day it
-- was done and lasts three years from it (config/volunteer_shifts.json validity_years).
CREATE TABLE IF NOT EXISTS public.volunteer_requirements (
  organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  requirement_key VARCHAR(40) NOT NULL
    CHECK (requirement_key IN ('background_check', 'safety_training', 'first_aid_certificate', 'driver_licence')),
  checked_on DATE,
  valid_until DATE,
  verified_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  verified_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (organization_id, user_id, requirement_key),
  CHECK (requirement_key <> 'background_check' OR (checked_on IS NOT NULL AND valid_until IS NOT NULL))
);

COMMENT ON TABLE public.volunteer_shifts IS 'Volunteer needs of one activity or camp, by time slot. Written through services/volunteerShifts.js, which locks the shift so its places are never exceeded.';
COMMENT ON TABLE public.volunteer_signups IS 'A member who took a place on a shift; the last place goes to one person only. Pending while the shift type''s requirements are not all verified for that person, confirmed once they are.';
COMMENT ON TABLE public.volunteer_requirements IS 'Requirements (background check, training…) a manager verified for a member of the unit, with their expiry. Visible to managers and to the person only.';
