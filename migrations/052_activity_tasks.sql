-- Shared tasks for outings/camps and planned meetings. Assignments expose no
-- participant records; unit administrators explicitly grant task permissions.
SELECT setval(pg_get_serial_sequence('public.permissions', 'id'),
  COALESCE((SELECT MAX(id) FROM public.permissions), 0) + 1, false);
INSERT INTO public.permissions (permission_key, permission_name, category, description)
VALUES
  ('tasks.view', 'View own tasks', 'tasks', 'Read assigned tasks and update their status; no access to youth records'),
  ('tasks.manage', 'Manage unit tasks', 'tasks', 'Create, assign and edit tasks for active unit members')
ON CONFLICT (permission_key) DO NOTHING;

CREATE UNIQUE INDEX IF NOT EXISTS activities_id_organization_unique ON public.activities (id, organization_id);
CREATE UNIQUE INDEX IF NOT EXISTS year_plan_meetings_id_organization_unique ON public.year_plan_meetings (id, organization_id);

CREATE TABLE IF NOT EXISTS public.activity_tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  activity_id INTEGER,
  meeting_id INTEGER,
  title VARCHAR(255) NOT NULL CHECK (length(btrim(title)) > 0),
  assignee_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  due_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'in_progress', 'done')),
  created_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (num_nonnulls(activity_id, meeting_id) = 1),
  FOREIGN KEY (activity_id, organization_id) REFERENCES public.activities(id, organization_id) ON DELETE CASCADE,
  FOREIGN KEY (meeting_id, organization_id) REFERENCES public.year_plan_meetings(id, organization_id) ON DELETE CASCADE,
  UNIQUE (id, organization_id)
);
CREATE INDEX IF NOT EXISTS activity_tasks_assignee_due ON public.activity_tasks (organization_id, assignee_id, due_date, id);

CREATE TABLE IF NOT EXISTS public.activity_task_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id INTEGER NOT NULL,
  organization_id INTEGER NOT NULL,
  previous_status VARCHAR(20),
  status VARCHAR(20) NOT NULL,
  changed_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (task_id, organization_id) REFERENCES public.activity_tasks(id, organization_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS activity_task_history_task ON public.activity_task_history (organization_id, task_id, id);
COMMENT ON TABLE public.activity_tasks IS 'Unit tasks linked to exactly one outing/camp or planned meeting. Only active members may be assigned through the shared task service.';
COMMENT ON TABLE public.activity_task_history IS 'Creation and status transitions, with actor and timestamp, committed atomically with the task.';
