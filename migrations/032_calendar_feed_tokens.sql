-- Calendar subscriptions: a private link a calendar app polls for the unit's
-- activities.
--
-- Calendar apps (Google, Apple, Outlook) fetch a URL on their own schedule and
-- cannot send the app's bearer token, so a subscription is a link that stands
-- for its holder. Like the emailed links of 007, it is an opaque random token
-- of which only the SHA-256 digest is stored (utils/invitation-tokens.js): a
-- read of this table yields nothing that opens a feed.
--
-- A link says who it acts for, never what they may see. Each fetch re-checks
-- the holder's active membership and activities.view through the shared
-- authorization engine, so leaving the unit or losing the permission closes
-- the feed at once, without anyone revoking it.
--
-- One active link per person and unit: making a new one revokes the old, which
-- is how someone who shared it by mistake takes it back.
--
-- Every statement is a no-op against a database that already has it.

CREATE TABLE IF NOT EXISTS public.calendar_feed_tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token_digest character(64) NOT NULL UNIQUE,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at timestamp with time zone,
    revoked_at timestamp with time zone
);

CREATE UNIQUE INDEX IF NOT EXISTS calendar_feed_tokens_one_active
    ON public.calendar_feed_tokens (organization_id, user_id)
    WHERE revoked_at IS NULL;

COMMENT ON TABLE public.calendar_feed_tokens IS
    'Private calendar subscription links. Only the SHA-256 of each token is stored; every fetch re-checks the holder''s membership and activities.view.';
COMMENT ON COLUMN public.calendar_feed_tokens.token_digest IS
    'Hex SHA-256 of the token in the subscription URL (utils/invitation-tokens.js). The token itself is shown once and never stored.';
COMMENT ON COLUMN public.calendar_feed_tokens.last_used_at IS
    'Last time a calendar app fetched the feed, shown to the holder so a link nobody uses can be recognised.';
COMMENT ON COLUMN public.calendar_feed_tokens.revoked_at IS
    'Set when the holder disables the link or makes a new one. A revoked link answers 404.';
