-- A unit's equipment catalogue: articles named once (name, category, unit of
-- measure, optional inventory item) and then chosen, with a quantity, in the
-- material of a schedule line. Free-text material stays as it was; the
-- catalogue only adds structured lines beside it, so camp lists can add
-- quantities up and reminders can name what to bring.
--
-- Items are archived, never deleted: a schedule line keeps naming an article
-- the unit no longer offers.
SELECT setval(pg_get_serial_sequence('public.permissions', 'id'),
  COALESCE((SELECT MAX(id) FROM public.permissions), 0) + 1, false);
INSERT INTO public.permissions (permission_key, permission_name, category, description)
VALUES
  ('equipment_catalog.manage', 'Manage the equipment catalogue', 'inventory',
   'Create, edit and archive the articles offered in activity material lists')
ON CONFLICT (permission_key) DO NOTHING;

CREATE UNIQUE INDEX IF NOT EXISTS year_plan_meeting_activities_id_organization_unique
  ON public.year_plan_meeting_activities (id, organization_id);

CREATE TABLE IF NOT EXISTS public.equipment_catalog_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  name VARCHAR(150) NOT NULL CHECK (length(btrim(name)) > 0),
  category VARCHAR(30) NOT NULL DEFAULT 'other'
    CHECK (category IN ('camping', 'kitchen', 'games', 'first_aid', 'tools', 'crafts', 'sports', 'water', 'lighting', 'other')),
  unit_of_measure VARCHAR(20) NOT NULL DEFAULT 'each'
    CHECK (unit_of_measure IN ('each', 'pair', 'set', 'box', 'pack', 'bag', 'roll', 'kg', 'l', 'm')),
  equipment_item_id INTEGER REFERENCES public.equipment_items(id) ON DELETE SET NULL,
  archived_at TIMESTAMPTZ,
  created_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (id, organization_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS equipment_catalog_items_active_name
  ON public.equipment_catalog_items (organization_id, lower(btrim(name)))
  WHERE archived_at IS NULL;

CREATE TABLE IF NOT EXISTS public.meeting_activity_equipment (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  meeting_activity_id INTEGER NOT NULL,
  catalog_item_id INTEGER NOT NULL,
  quantity NUMERIC(10, 2) NOT NULL CHECK (quantity > 0),
  UNIQUE (meeting_activity_id, catalog_item_id),
  FOREIGN KEY (meeting_activity_id, organization_id)
    REFERENCES public.year_plan_meeting_activities(id, organization_id) ON DELETE CASCADE,
  FOREIGN KEY (catalog_item_id, organization_id)
    REFERENCES public.equipment_catalog_items(id, organization_id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS meeting_activity_equipment_item
  ON public.meeting_activity_equipment (organization_id, catalog_item_id);

COMMENT ON TABLE public.equipment_catalog_items IS
  'Articles a unit names once and offers in every material list of the unit. Archived (archived_at), never deleted, so schedule lines keep their articles.';
COMMENT ON COLUMN public.equipment_catalog_items.equipment_item_id IS
  'Optional inventory item this article corresponds to, among the equipment the unit may use.';
COMMENT ON TABLE public.meeting_activity_equipment IS
  'Catalogue articles and quantities a schedule line needs, beside its free-text material.';
