CREATE TABLE IF NOT EXISTS public.camp_equipment_lots (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
 meeting_id INTEGER NOT NULL,
 name VARCHAR(150) NOT NULL CHECK (length(btrim(name)) > 0),
 status TEXT NOT NULL DEFAULT 'to_prepare' CHECK (status IN ('to_prepare', 'loaded', 'returned')),
 version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
 creation_key UUID NOT NULL,
 creation_hash TEXT NOT NULL,
 created_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 FOREIGN KEY (meeting_id, organization_id) REFERENCES public.year_plan_meetings(id, organization_id) ON DELETE CASCADE,
 UNIQUE (id, organization_id), CONSTRAINT camp_equipment_lots_creation_key UNIQUE (organization_id, creation_key)
);
CREATE UNIQUE INDEX IF NOT EXISTS camp_equipment_lots_name ON public.camp_equipment_lots (organization_id, meeting_id, LOWER(BTRIM(name)));

CREATE TABLE IF NOT EXISTS public.camp_equipment_lot_items (
 lot_id INTEGER NOT NULL,
 organization_id INTEGER NOT NULL,
 item_key TEXT NOT NULL CHECK (item_key ~ '^[ae][1-9][0-9]*$'),
 name TEXT NOT NULL,
 unit_of_measure TEXT NOT NULL,
 quantity NUMERIC(10,2) NOT NULL CHECK (quantity > 0),
 PRIMARY KEY (lot_id, item_key),
 FOREIGN KEY (lot_id, organization_id) REFERENCES public.camp_equipment_lots(id, organization_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS public.camp_equipment_lot_roles (
 lot_id INTEGER NOT NULL,
 organization_id INTEGER NOT NULL,
 role TEXT NOT NULL CHECK (role IN ('prepare', 'transport', 'return')),
 task_id INTEGER NOT NULL,
 PRIMARY KEY (lot_id, role),
 UNIQUE (task_id),
 FOREIGN KEY (lot_id, organization_id) REFERENCES public.camp_equipment_lots(id, organization_id) ON DELETE CASCADE,
 FOREIGN KEY (task_id, organization_id) REFERENCES public.activity_tasks(id, organization_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS public.camp_equipment_lot_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lot_id INTEGER NOT NULL,
 organization_id INTEGER NOT NULL,
 version INTEGER NOT NULL,
 action TEXT NOT NULL CHECK (action IN ('created', 'edited', 'status')),
 previous_status TEXT,
 status TEXT NOT NULL,
 changed_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 FOREIGN KEY (lot_id, organization_id) REFERENCES public.camp_equipment_lots(id, organization_id) ON DELETE CASCADE,
 UNIQUE (lot_id, version)
);
CREATE TABLE IF NOT EXISTS public.camp_equipment_lot_receipts (
 organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
 actor_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
 mutation_id UUID NOT NULL,
 request_hash TEXT NOT NULL,
 response_data JSONB,
 PRIMARY KEY (organization_id, actor_id, mutation_id)
);
COMMENT ON TABLE public.camp_equipment_lot_items IS 'Validated camp-list entries snapshotted when assigned; metadata is never supplied by the client.';
COMMENT ON TABLE public.camp_equipment_lot_roles IS 'One shared task per lot role. The task owns the assignee and due date; no duplicate assignee fields.';
