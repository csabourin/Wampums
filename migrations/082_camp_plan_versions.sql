-- Camp plan, slice 3 (#1418): submitting the plan freezes a version.
--
-- A version keeps what the plan said when it was submitted, so that later
-- changes to the camp, its site or the unit's templates never change a plan
-- already submitted (or, in slice 4, approved):
--
-- - `snapshot`: the plan's content as read at submission (header, checklist,
--   written sections with the template texts then in force, schedule, site,
--   team, youth, material). It holds no health information.
-- - `snapshot_sha256`: SHA-256 of the snapshot (keys sorted) with the camp and
--   version number. Its first eight characters are the verification code
--   printed on the PDF's first page and shown in Wampums, so anyone can see that
--   a copy is this version by comparing two short codes.
-- - `pdf`: the document generated by the server from that snapshot, in the
--   unit's language, and `pdf_sha256` its digest, so a copy attached to the
--   SISC can be checked against the version.
-- - `pdf_health` / `pdf_health_sha256`: the same document with the allergies
--   section, served only to holders of `camp_allergies.view`. NULL when the
--   plan had no health information to show.
--
-- A new submission supersedes the version still waiting. Slice 4 (#1419)
-- records approvals against a version; `status` already names its states.

CREATE TABLE IF NOT EXISTS public.camp_plan_versions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  meeting_id INTEGER NOT NULL,
  version_number INTEGER NOT NULL CHECK (version_number > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'submitted'
    CHECK (status IN ('submitted', 'changes_requested', 'approved', 'superseded')),
  language VARCHAR(12) NOT NULL,
  snapshot JSONB NOT NULL,
  snapshot_sha256 CHAR(64) NOT NULL CHECK (snapshot_sha256 ~ '^[0-9a-f]{64}$'),
  pdf BYTEA NOT NULL,
  pdf_sha256 CHAR(64) NOT NULL CHECK (pdf_sha256 ~ '^[0-9a-f]{64}$'),
  pdf_health BYTEA,
  pdf_health_sha256 CHAR(64) CHECK (pdf_health_sha256 IS NULL OR pdf_health_sha256 ~ '^[0-9a-f]{64}$'),
  submitted_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((pdf_health IS NULL) = (pdf_health_sha256 IS NULL)),
  UNIQUE (organization_id, meeting_id, version_number),
  UNIQUE (id, organization_id),
  FOREIGN KEY (meeting_id, organization_id)
    REFERENCES public.year_plan_meetings(id, organization_id) ON DELETE CASCADE
);

COMMENT ON TABLE public.camp_plan_versions IS
  'Frozen versions of a camp plan (#1418): the content and the server-generated PDF as submitted, never changed afterwards. Health information lives only in pdf_health, served to holders of camp_allergies.view.';
COMMENT ON COLUMN public.camp_plan_versions.snapshot IS
  'The plan as read when submitted, without health information. Compared with the current plan to show what changed since.';
COMMENT ON COLUMN public.camp_plan_versions.pdf_sha256 IS
  'SHA-256 of pdf, shown to people so a copy attached elsewhere can be checked against this version.';
