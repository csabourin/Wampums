-- Camp sites (#1317): the places a unit camps at, named once and chosen for each camp, with
-- what the camp permit asks about them (owner, accommodation, heating, insurance) and how to
-- reach help from there (nearest hospital, poison centre, directions). Sites are archived,
-- never deleted, so a camp keeps the site it was held at.
-- camp_details holds what belongs to one camp: its site, season and accommodation, who leads
-- on site, and the number families call. Allowed values are config/camp_sites.json.
SELECT setval(pg_get_serial_sequence('public.permissions', 'id'),
  COALESCE((SELECT MAX(id) FROM public.permissions), 0) + 1, false);
INSERT INTO public.permissions (permission_key, permission_name, category, description)
VALUES ('camp_sites.manage', 'Manage camp sites', 'camp_sites', 'Add, edit and archive the places the unit camps at, with their emergency resources')
ON CONFLICT (permission_key) DO NOTHING;

-- Whoever plans the unit's meetings and camps manages the places they are held at.
INSERT INTO public.role_permissions (role_id, permission_id)
SELECT DISTINCT r.id, p.id FROM public.roles r CROSS JOIN public.permissions p
WHERE p.permission_key = 'camp_sites.manage' AND r.data_scope = 'organization' AND EXISTS (
  SELECT 1 FROM public.role_permissions rp JOIN public.permissions held ON held.id = rp.permission_id
   WHERE rp.role_id = r.id AND held.permission_key = 'meetings.manage')
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS public.camp_sites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  name VARCHAR(150) NOT NULL CHECK (length(btrim(name)) > 0),
  owner_name VARCHAR(255),
  address TEXT CHECK (length(address) <= 4000),
  province VARCHAR(2) CHECK (province IN ('AB','BC','MB','NB','NL','NS','NT','NU','ON','PE','QC','SK','YT')),
  phone VARCHAR(40),
  site_type VARCHAR(255),
  description TEXT CHECK (length(description) <= 4000),
  accommodation TEXT CHECK (accommodation IN ('tent', 'cabin', 'shelter', 'other')),
  accommodation_note VARCHAR(255),
  heating TEXT CHECK (heating IN ('none', 'electricity', 'gas', 'wood', 'other')),
  heating_note VARCHAR(255),
  has_own_insurance BOOLEAN,
  insurance_note TEXT CHECK (length(insurance_note) <= 4000),
  hospital_name VARCHAR(255),
  hospital_address TEXT CHECK (length(hospital_address) <= 4000),
  hospital_phone VARCHAR(40),
  hospital_travel_minutes INTEGER CHECK (hospital_travel_minutes BETWEEN 0 AND 1440),
  hospital_distance_km NUMERIC(6,1) CHECK (hospital_distance_km BETWEEN 0 AND 9999),
  poison_centre_phone VARCHAR(40),
  other_emergency_numbers TEXT CHECK (length(other_emergency_numbers) <= 4000),
  directions_url VARCHAR(2000) CHECK (directions_url ~* '^https?://'),
  hospital_directions_url VARCHAR(2000) CHECK (hospital_directions_url ~* '^https?://'),
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
  archived_at TIMESTAMPTZ,
  created_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (id, organization_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS camp_sites_active_name
  ON public.camp_sites (organization_id, LOWER(BTRIM(name))) WHERE archived_at IS NULL;

CREATE TABLE IF NOT EXISTS public.camp_details (
  organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  meeting_id INTEGER NOT NULL,
  camp_site_id INTEGER,
  season TEXT CHECK (season IN ('summer', 'autumn', 'winter', 'spring')),
  accommodation TEXT CHECK (accommodation IN ('tent', 'cabin', 'shelter', 'other')),
  on_site_lead_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  contact_phone VARCHAR(40),
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
  updated_by UUID REFERENCES public.users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (organization_id, meeting_id),
  FOREIGN KEY (meeting_id, organization_id) REFERENCES public.year_plan_meetings(id, organization_id) ON DELETE CASCADE,
  FOREIGN KEY (camp_site_id, organization_id) REFERENCES public.camp_sites(id, organization_id)
);
CREATE INDEX IF NOT EXISTS camp_details_site ON public.camp_details (organization_id, camp_site_id);

COMMENT ON TABLE public.camp_sites IS 'Places a unit camps at, with the camp permit''s site and emergency information. Archived, never deleted. No personal data: phones are the site''s, the hospital''s and public lines.';
COMMENT ON TABLE public.camp_details IS 'One planned camp''s site, season, accommodation, on-site lead (an active member) and the number families call in an emergency.';
COMMENT ON COLUMN public.camp_details.contact_phone IS 'Number families call during the camp; when empty, the site''s phone is shown. Never a member''s personal number unless they entered it here themselves.';
